export type TimedChar = {
  /** The character itself */
  c: string;
  /** Reveal time in seconds, relative to the start of this scene's audio */
  t: number;
};

export type TargetMarker = {
  /** Center position in percent within the native 16:9 illustration. */
  x: number;
  y: number;
  source: 'visual-review' | 'tts-boundary' | 'scene-default';
  confidence: number;
  reviewer: string;
};

export type VisualRequirements = {
  mustShow: string[];
  mustNotShow: string[];
  action: string;
  continuity: string[];
  /** Present only when an action is essential to plot, vocabulary recognition, or continuity. */
  criticalAction?: {
    subject: string;
    bodyPartOrTool: string;
    object: string;
    contact: string;
    relativePosition: string;
    direction: string;
    result: string;
    forbiddenAlternatives: string[];
  };
};

export type ImageGeneration = {
  /** Earlier scenes whose approved image or prop state is required by this scene. */
  dependsOn: string[];
  /** Explicit causes that make this scene serial rather than part of a parallel batch. */
  serialReasons: Array<'continuous-action' | 'prop-state' | 'previous-image-reference' | 'manual'>;
};

export type CharacterProfile = {
  id: string;
  name: string;
  role: string;
  appearance: string;
  mustKeep: string[];
};

export type VisualBible = {
  /** Project-specific style and palette, created after the story is approved. */
  stylePrompt: string;
  palette: string;
  characters: CharacterProfile[];
  /** Project-specific reference sheet under public/. Never a built-in cast. */
  referenceImage: string;
};

export type TargetHighlight = {
  word: string;
  /** Exact spelling submitted by the user and shown in the on-screen label. */
  displayWord: string;
  start: number;
  /** Actual pronunciation length returned by the TTS WordBoundary event. */
  spokenDurationSec: number;
  /** On-screen duration, independent from pronunciation and optional audio pause. */
  visualDurationSec: number;
};

export type Scene = {
  /** Two-digit scene id, e.g. "01" */
  id: string;
  /** Big headline shown above the image */
  title: string;
  /** Chinese caption (also the narration text) */
  zh: string;
  /** Path under public/, e.g. "assets/scene-01.png" (native 16:9 full-color image) */
  image: string;
  /** Path under public/, e.g. "audio/scene-01.mp3" — filled by tts_generate.py */
  audio?: string;
  /** Narration length in seconds — filled by tts_generate.py */
  audioDurationSec?: number;
  /** Per-character reveal times — filled by tts_generate.py */
  zhChars?: TimedChar[];
  /** Word-level highlight events, filled by tts_generate.py. */
  targetHighlights?: TargetHighlight[];
  /** Derived tail needed only when a target label extends past narration. */
  visualTailSec?: number;
  /** Per-word object locations authored for this scene's illustration. */
  targetMarkers?: Record<string, TargetMarker>;
  /** IDs from story.visualBible.characters visible in this scene. */
  characterIds?: string[];
  /** Dependency metadata used to plan safe illustration batches of at most three scenes. */
  imageGeneration?: ImageGeneration;
  /** Prompt used to generate the image (kept for the record; not rendered) */
  imagePrompt?: string;
  /** Machine-readable semantic contract, verified after image generation. */
  visualRequirements: VisualRequirements;
};

export type Theme = {
  /** Page background */
  bg: string;
  /** Card background behind the illustration */
  card: string;
  /** Primary text */
  ink: string;
  /** Secondary text (header, english caption) */
  muted: string;
  /** Accent (underline, caption bar) */
  accent: string;
  /** Scene number badge */
  badge: string;
};

export type StoryMeta = {
  schemaVersion: 2;
  /** e.g. "亲子" */
  category: string;
  /** e.g. "成长不会提醒" */
  series: string;
  width: number;
  height: number;
  /** Stable normalized scene illustration dimensions; fixed at 1280×720. */
  imageWidth: number;
  imageHeight: number;
  fps: number;
  ttsProvider: 'edge' | 'azure';
  voice: string;
  rate: string;
  imageNormalization: 'stable-lanczos';
  imageAspectTolerancePct: number;
  targetPauseSec: number;
  targetVisualDurationSec: number;
  introTailSec: number;
  durationTarget: {
    targetSec: number;
    idealMinSec: number;
    idealMaxSec: number;
    acceptableMinSec: number;
    acceptableMaxSec: number;
    maxCreativeAdjustments: number;
  };
  pauseTargets: string[];
  introTitle: string;
  /** Chinese narration of the all-Chinese title, generated by tts_generate.py. */
  introAudio?: string;
  /** Actual duration of introAudio; controls when the first scene begins. */
  introAudioDurationSec?: number;
  theme: Theme;
};

export type Story = {
  meta: StoryMeta;
  visualBible: VisualBible;
  scenes: Scene[];
};
